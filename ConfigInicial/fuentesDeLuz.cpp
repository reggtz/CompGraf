	GLuint VBO, VAO;
	glGenVertexArrays(1, &VAO);
	glGenBuffers(1, &VBO);
	glBindVertexArray(VAO);
	glBindBuffer(GL_ARRAY_BUFFER, VBO);
	glBufferData(GL_ARRAY_BUFFER, sizeof(vertices), vertices, GL_STATIC_DRAW);
	// Position attribute
	glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, 6 * sizeof(GLfloat), (GLvoid*)0);
	glEnableVertexAttribArray(0);
	// normal attribute
	glVertexAttribPointer(1, 3, GL_FLOAT, GL_FALSE, 6 * sizeof(float), (void*)(3 * sizeof(float)));
	glEnableVertexAttribArray(1);

	// Comprobar que ambos programas de shaders se enlazaron correctamente.
	GLint lightingLinked = GL_FALSE;
	GLint lampLinked = GL_FALSE;
	glGetProgramiv(lightingShader.Program, GL_LINK_STATUS, &lightingLinked);
	glGetProgramiv(lampShader.Program, GL_LINK_STATUS, &lampLinked);
	if (lightingLinked != GL_TRUE || lampLinked != GL_TRUE)
	{
		GLchar log[2048] = {};
		GLuint failedProgram = lightingLinked != GL_TRUE
			? lightingShader.Program : lampShader.Program;
		glGetProgramInfoLog(failedProgram, sizeof(log), nullptr, log);
		std::cerr << "Error al enlazar shaders: " << log << std::endl;
		glfwDestroyWindow(window);
		glfwTerminate();
		return EXIT_FAILURE;
	}

	glBindVertexArray(0);
	glEnable(GL_DEPTH_TEST);
	glDisable(GL_BLEND);
	glDepthMask(GL_TRUE);

